const POPULAR_STYLES = EXTRA_STYLES.filter((style) => style.category === "Popular");
const OTHER_EXTRA_STYLES = EXTRA_STYLES.filter((style) => style.category !== "Popular");

export const FILM_STYLES: FilmStyle[] = [...POPULAR_STYLES, ...CORE_STYLES, ...OTHER_EXTRA_STYLES];

export function getFilmStyle(id: string): FilmStyle | undefined {
  return FILM_STYLES.find((style) => style.id === id);
}

export function searchFilmStyles(query: string, category?: FilmCategory | "All"): FilmStyle[] {
  const q = query.trim().toLowerCase();
  return FILM_STYLES.filter((style) => {
    if (category && category !== "All" && style.category !== category) return false;
    if (!q) return true;
    return (
      style.name.toLowerCase().includes(q) ||
      style.description.toLowerCase().includes(q) ||
      style.category.toLowerCase().includes(q)
    );
  });
}
